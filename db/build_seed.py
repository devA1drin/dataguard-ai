"""Build db/seed.sql from the synthetic CSVs in data/generated/.

Run after `python data/generate.py`. Requires the `bcrypt` package.
Seeds: demo users (one per role), customers, consents (+ initial history), recent
access logs (unscored - the backend scoring job scores them via the ML service on
startup, which also creates alerts), sample incidents (unclassified - classified by
the same job) and a few data-rights requests.

Access-log timestamps are made relative to the moment the seed is loaded (most recent
synthetic day = "yesterday", Philippine time), so the dashboard looks current whenever
`docker compose up` runs. Note: the stored `is_weekend` feature comes from the generator's
calendar and may not match the shifted weekday.
"""
from __future__ import annotations

import csv
from datetime import datetime, timedelta, timezone
from pathlib import Path

import bcrypt

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "data" / "generated"
DEMO_PASSWORD = "DemoPass123!"   # demo only - documented in README
LOG_DAYS = 21                    # how many recent days of access logs to seed
N_INCIDENTS = 28


def q(v) -> str:
    if v is None or v == "":
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def read(name):
    with open(GEN / name, encoding="utf-8") as f:
        return list(csv.DictReader(f))


NOISE_PREFIXES = ("Reported by", "The incident", "Initial assessment", "No confirmation", "The affected",
                  "IT security", "Further details", "This may")


def _title(description: str) -> str:
    """Use the first substantive sentence (not a boilerplate 'noise' sentence) as the incident title."""
    sentences = [s.strip() for s in description.replace("; ", ". ").split(". ") if s.strip()]
    for s in sentences:
        if not s.startswith(NOISE_PREFIXES):
            s = s.rstrip(".")
            return s if len(s) <= 90 else s[:87].rsplit(" ", 1)[0] + "..."
    return sentences[0][:90]


def main():
    out = ["-- AUTO-GENERATED by db/build_seed.py from SYNTHETIC data. Do not edit by hand.", "BEGIN;"]
    customers = read("customers.csv")
    out.append("INSERT INTO customers (id, full_name, email, phone, city, created_at) VALUES")
    out.append(",\n".join(f"({c['customer_id']},{q(c['full_name'])},{q(c['email'])},{q(c['phone'])},{q(c['city'])},{q(c['created_at'])})"
                          for c in customers) + ";")
    out.append("SELECT setval('customers_id_seq', (SELECT max(id) FROM customers));")

    h = bcrypt.hashpw(DEMO_PASSWORD.encode(), bcrypt.gensalt(10)).decode()
    users = [("customer@dataguard.demo", customers[0]["full_name"], "customer", 1),
             ("customer2@dataguard.demo", customers[1]["full_name"], "customer", 2),
             ("dpo@dataguard.demo", "Dana Pascual (DPO)", "dpo", None),
             ("security@dataguard.demo", "Sam Reyes (Security)", "security", None),
             ("admin@dataguard.demo", "Alex Cruz (Admin)", "admin", None),
             ("exec@dataguard.demo", "Erika Santos (Executive)", "executive", None)]
    out.append("INSERT INTO users (email, password_hash, full_name, role, customer_id) VALUES")
    out.append(",\n".join(f"({q(e)},{q(h)},{q(n)},{q(r)},{q(c)})" for e, n, r, c in users) + ";")

    cons = read("consents.csv")
    out.append("INSERT INTO consents (customer_id, purpose, granted, updated_at) VALUES")
    out.append(",\n".join(f"({c['customer_id']},{q(c['purpose'])},{c['granted'].lower()},now() - interval '60 days')" for c in cons) + ";")
    out.append("INSERT INTO consent_history (customer_id, purpose, granted, channel, changed_at) "
               "SELECT customer_id, purpose, granted, 'signup', updated_at FROM consents;")

    logs = read("access_logs.csv")
    last_day = datetime.fromisoformat(logs[-1]["timestamp"]).date()
    first_keep = last_day - timedelta(days=LOG_DAYS - 1)
    # Timestamps are computed when the seed is LOADED: the generator's last day becomes
    # "yesterday" (Philippine time), keeping the original time of day.
    out.append("CREATE FUNCTION pg_temp.ph_ts(days_ago int, t time) RETURNS timestamptz AS $$ "
               "SELECT (((now() AT TIME ZONE 'Asia/Manila')::date - days_ago) + t) AT TIME ZONE 'Asia/Manila' $$ LANGUAGE sql;")
    rows = []
    for r in logs:
        ts = datetime.fromisoformat(r["timestamp"])
        if ts.date() < first_keep:
            continue
        days_ago = (last_day - ts.date()).days + 1
        rows.append(f"(pg_temp.ph_ts({days_ago}, '{ts.time().isoformat()}'),{q(r['employee_id'])},{q(r['role'])},{q(r['resource'])},{r['customer_id']},"
                    f"{r['hour_of_day']},{r['records_accessed']},{r['distinct_customers']},{r['off_hours']},{r['is_weekend']},"
                    f"{r['export_flag']},{r['failed_logins']},{'true' if r['is_anomaly'] == '1' else 'false'},{q(r['anomaly_type'])})")
    out.append("INSERT INTO access_logs (ts, employee_id, employee_role, resource, customer_id, hour_of_day, records_accessed, "
               "distinct_customers, off_hours, is_weekend, export_flag, failed_logins, synthetic_label, synthetic_type) VALUES")
    out.append(",\n".join(rows) + ";")

    incs = read("incidents.csv")[:N_INCIDENTS]
    sev = ["low", "medium", "medium", "high", "critical", "medium", "high"]
    st = ["open", "open", "investigating", "contained", "resolved", "closed", "investigating"]
    vals = []
    for i, r in enumerate(incs):
        title = _title(r["description"])
        days_ago = (N_INCIDENTS - i) % 30
        vals.append(f"({q(title)},{q(r['description'])},{q(sev[i % len(sev)])},{q(st[i % len(st)])},3,"
                    f"{'4' if i % 3 else 'NULL'},now() - interval '{days_ago} days')")
    out.append("INSERT INTO incidents (title, description, severity, status, reported_by, assigned_to, reported_at) VALUES")
    out.append(",\n".join(vals) + ";")
    out.append("""INSERT INTO incident_actions (incident_id, action_type, content, completed, actor_id, created_at) VALUES
(1,'note','Initial triage done; affected system identified.',false,3,now() - interval '20 days'),
(1,'corrective_action','Reset credentials of affected account and enable MFA.',true,4,now() - interval '19 days'),
(2,'corrective_action','Review export permissions for the reporting team.',false,3,now() - interval '10 days');""")

    out.append("""INSERT INTO data_requests (reference, customer_id, type, details, status, response, created_at, updated_at) VALUES
('DR-2026-0001',1,'access','Please send me a copy of all personal data you hold about me.','completed','Your data export was provided through the portal.',now() - interval '30 days',now() - interval '25 days'),
('DR-2026-0002',1,'correction','My delivery address changed to Quezon City.','in_review',NULL,now() - interval '3 days',now() - interval '2 days'),
('DR-2026-0003',2,'deletion','Please delete my account and marketing data.','submitted',NULL,now() - interval '1 day',now() - interval '1 day');""")
    out.append("UPDATE data_requests SET due_at = created_at + interval '21 days';")
    out.append("COMMIT;")
    (ROOT / "db" / "seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote db/seed.sql ({len(rows)} access logs, {len(incs)} incidents, {len(users)} users)")


if __name__ == "__main__":
    main()
