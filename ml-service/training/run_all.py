"""One-shot pipeline: generate synthetic data -> train -> evaluate -> write models/metrics.json.

Usage (from ml-service/):  python -m training.run_all  [--skip-generate]
"""
from __future__ import annotations

import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from training import train_anomaly, train_incidents, train_phishing  # noqa: E402


def main():
    if "--skip-generate" not in sys.argv:
        subprocess.run([sys.executable, str(ROOT.parent / "data" / "generate.py")], check=True)
    print("\n== Anomaly detector ==")
    anomaly = train_anomaly.main()
    print("\n== Incident classifiers ==")
    incidents = train_incidents.main()
    print("\n== Phishing detector ==")
    phishing = train_phishing.main()
    metrics = {"generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
               "data_note": "All metrics computed on SYNTHETIC data generated by data/generate.py (seed 42).",
               "anomaly_detection": anomaly, "incident_classification": incidents,
               "phishing_detection": phishing}
    (ROOT / "models" / "metrics.json").write_text(json.dumps(metrics, indent=2))
    print("\nWrote", ROOT / "models" / "metrics.json")


if __name__ == "__main__":
    main()
